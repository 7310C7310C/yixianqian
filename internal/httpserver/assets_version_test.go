func TestRootRenderIsPrecompiled(t *testing.T) {
	render := readEmbedded(t, "static/legacy/app.render.js")
	if !strings.HasPrefix(render, "/* generated by tools/spa_precompile/precompile.mjs; vue=") {
		t.Fatal("app.render.js is missing the generated header")
	}
	if !strings.Contains(render, "window.__YXQ_RENDER__ = render") {
		t.Fatal("app.render.js does not assign window.__YXQ_RENDER__")
	}
	if strings.Contains(render, "eval(") || strings.Contains(render, "new Function") {
		t.Fatal("app.render.js must not use eval/new Function (CSP)")
	}
	if regexp.MustCompile(`(?m)^\s*(import|export)\s`).MatchString(render) {
		t.Fatal("app.render.js still contains ESM syntax")
	}
	html := readEmbedded(t, "static/legacy/index.html")
	if !strings.Contains(html, "app.render.js?v=__ASSET_URL_VERSION__") {
		t.Fatal("index.html does not load the precompiled render bundle")
	}
	js := readEmbedded(t, "static/legacy/app.js")
	if !strings.Contains(js, "render: window.__YXQ_RENDER__") {
		t.Fatal("app.js does not use the precompiled render function")
	}
}

