#!/usr/bin/env node
// Dev-time minify: web/static/legacy/app.js -> web/static/legacy/app.min.js
//
// 生成物已提交，部署与 CI 不需要 Node（门禁见 tools/spa_minify/check.py +
// tools/test_spa_minify.py）。改 app.js 后必须重跑 `npm run build` 并提交
// app.min.js、app.min.manifest.json 与 app.min.js.gz（`make static-gzip`）。
//
// 语义约束：
// - app.js 是 classic script（非 ESM）：这里用 transform 而不是 bundle，
//   保持顶层作用域语义；
// - target 对齐浏览器下限（iOS 14.5 / Safari 14.1、Chrome 84、Firefox 74）；
// - 不改任何字面量/分支/事件，只做语法等价的压缩；
// - 顶栏 banner 里写来源 sha256 前 12 位，方便人眼确认「生成物对应哪版源」。
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import zlib from 'node:zlib'
import { fileURLToPath } from 'node:url'
import { transform } from 'esbuild'

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, '../..')
const srcFile = path.join(repo, 'web/static/legacy/app.js')
const outFile = path.join(repo, 'web/static/legacy/app.min.js')
const manifestFile = path.join(repo, 'web/static/legacy/app.min.manifest.json')

// safari14（无 14.1）在 esbuild 里会把解构降级到不支持的目标而直接报错；
// 项目浏览器下限是 iOS 14.5 / Safari 14.1，用 safari14.1 与项目口径一致。
const TARGET = ['safari14.1', 'chrome84', 'firefox74']

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex')
const gzipSize = (buf) => zlib.gzipSync(buf, { level: 9 }).length

async function build () {
  const source = fs.readFileSync(srcFile)
  const sourceSha = sha256(source)
  const banner = `/*! generated by tools/spa_minify from app.js sha256:${sourceSha.slice(0, 12)} (do not edit) */`
  const result = await transform(source, {
    loader: 'js',
    minify: true,
    target: TARGET,
    legalComments: 'none',
    banner,
    charset: 'utf8',
    sourcefile: 'app.js'
  })
  return { source, sourceSha, code: Buffer.from(result.code, 'utf8') }
}

function writeArtifacts (source, sourceSha, code) {
  fs.writeFileSync(outFile, code)
  const esbuildPkg = JSON.parse(fs.readFileSync(path.join(here, 'node_modules/esbuild/package.json'), 'utf8'))
  const manifest = {
    source: { path: 'app.js', bytes: source.length, sha256: sourceSha },
    min: { path: 'app.min.js', bytes: code.length, sha256: sha256(code) },
    tool: { name: 'esbuild', version: esbuildPkg.version, target: TARGET }
  }
  fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n')
  return manifest
}

const check = process.argv.includes('--check')
const { source, sourceSha, code } = await build()

if (check) {
  if (!fs.existsSync(outFile)) {
    console.error('app.min.js missing (run: npm run build)')
    process.exit(1)
  }
  const committed = fs.readFileSync(outFile)
  if (sha256(committed) !== sha256(code)) {
    console.error('app.min.js is stale: rebuild with `cd tools/spa_minify && npm run build`')
    console.error(`  committed ${committed.length}B sha=${sha256(committed).slice(0, 12)}`)
    console.error(`  rebuilt   ${code.length}B sha=${sha256(code).slice(0, 12)}`)
    process.exit(1)
  }
  console.log(`app.min.js ok: ${committed.length}B raw, ${gzipSize(committed)}B gzip, sha=${sha256(committed).slice(0, 12)}`)
} else {
  const manifest = writeArtifacts(source, sourceSha, code)
  console.log(`app.js ${source.length}B (${gzipSize(source)}B gzip) -> app.min.js ${manifest.min.bytes}B (${gzipSize(code)}B gzip)`)
  console.log(`manifest: ${path.relative(repo, manifestFile)} esbuild=${manifest.tool.version}`)
}
