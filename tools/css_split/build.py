#!/usr/bin/env python3
"""把 app.css 拆成「首屏 critical」与其余：

- 输入 `web/static/legacy/app.css`（源，保持不动）
- 输出 `web/static/legacy/app.critical.css`（生成物，壳内联 ≤15KB gzip）
- 壳改为内联 critical + 异步加载完整 app.css

为什么用「复制子集」而不是搬移：app.css 仍是唯一源，critical 只是其中的顶层块副本，
check.py 会校验每个块都能在 app.css 里逐字找到，避免两边漂移；也不存在搬移时漏规则
导致样式丢失的风险（完整 app.css 仍会异步到达）。

    python3 tools/css_split/build.py          # 生成 app.critical.css
    python3 tools/css_split/check.py          # 校验（make spa-check 会跑）
"""

from __future__ import annotations

import gzip
import hashlib
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
LEGACY = REPO / "web" / "static" / "legacy"
SOURCE = LEGACY / "app.css"
OUTPUT = LEGACY / "app.critical.css"
MANIFEST = LEGACY / "app.critical.manifest.json"

# 首屏（壳 + 首卡 + 底栏 + 登录/错误/骨架）需要的顶层块。其余（消息/活动/资料/
# 管理台等子页）由异步 app.css 补齐。
KEEP_PREFIXES = (
    ":root",
    "html",
    "html, body",
    "#app",
    "#boot-skeleton",
    "body",
    "*",
    ".van-theme-dark",
    ".tab-main",
    ".page",
    ".cards-page",
    ".swipe-card",
    ".swipe-guide",   # 首屏滑动引导遮罩：缺 position:fixed 会把它当普通块，把首卡顶下去
    ".sg-",
    ".filter-btn",    # 首卡顶部的筛选按钮：绝对定位，缺失会把卡片顶下去 11px
    ".card-top-left",
    ".card-actions",
    ".info-",         # 首卡资料网格：缺失会在 app.css 到达时把卡片正文撑高（CLS）
    ".profile-section-title",  # 首卡资料小标题字号（16→15px），缺失会造成 10px 位移
    ".hearts-",       # 首卡底部爱心/计数行（reviwer M9）
    ".card-",
    ".boot-",
    ".app-boot-",
    ".login-",
    ".theme-toggle",
    ".update-bar",
    ".van-tabbar",
    ".van-nav-bar",
    ".van-loading",
    ".van-empty",
    ".van-dialog",
    ".van-popup",
    ".van-toast",
    ".van-cell",
    ".van-tag",
    ".van-button",
    ".van-field",
)


def split_blocks(css: str) -> list[str]:
    """按顶层 `{...}` 切块（@media 等嵌套块算一块）。"""
    blocks: list[str] = []
    depth = 0
    start = 0
    for i, ch in enumerate(css):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                blocks.append(css[start : i + 1])
                start = i + 1
    tail = css[start:]
    if tail.strip():
        blocks.append(tail)
    return blocks


def selector_of(block: str) -> str:
    head = block.split("{", 1)[0]
    # 去掉块前注释，只留选择器文本
    head = re.sub(r"/\*.*?\*/", " ", head, flags=re.S)
    return " ".join(head.split())


def is_critical(selector: str) -> bool:
    if not selector:
        return False
    for part in selector.split(","):
        part = part.strip()
        if not part:
            continue
        if any(part.startswith(prefix) for prefix in KEEP_PREFIXES):
            return True
    return False


def build() -> tuple[str, dict]:
    css = SOURCE.read_text(encoding="utf-8")
    blocks = split_blocks(css)
    kept = [b.strip() for b in blocks if is_critical(selector_of(b))]
    body = "\n".join(kept) + "\n"
    source_sha = hashlib.sha256(css.encode()).hexdigest()
    header = (
        "/*! generated by tools/css_split from app.css sha256:%s "
        "(首屏 critical 子集；完整样式见 app.css，异步加载) */\n" % source_sha[:12]
    )
    text = header + body
    manifest = {
        "source": {"path": "app.css", "bytes": len(css.encode()), "sha256": source_sha},
        "critical": {
            "path": "app.critical.css",
            "bytes": len(text.encode()),
            "gzip_bytes": len(gzip.compress(text.encode(), 9)),
            "sha256": hashlib.sha256(text.encode()).hexdigest(),
            "blocks": len(kept),
        },
        "keep_prefixes": list(KEEP_PREFIXES),
    }
    return text, manifest


def main() -> int:
    check = "--check" in sys.argv
    text, manifest = build()
    if check:
        if not OUTPUT.exists():
            print("app.critical.css missing (run tools/css_split/build.py)", file=sys.stderr)
            return 1
        if OUTPUT.read_text(encoding="utf-8") != text:
            print("app.critical.css is stale (rerun tools/css_split/build.py)", file=sys.stderr)
            return 1
        print(f"app.critical.css ok: {manifest['critical']['bytes']}B raw, "
              f"{manifest['critical']['gzip_bytes']}B gzip, {manifest['critical']['blocks']} blocks")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO)}: {manifest['critical']['bytes']}B raw, "
          f"{manifest['critical']['gzip_bytes']}B gzip, {manifest['critical']['blocks']} blocks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
